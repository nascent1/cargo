<template>
  <div class="space-y-6 animate-fade-in-up max-w-3xl mx-auto">


    <!-- Loading State -->
    <div v-if="loading" class="flex justify-center py-12">
      <div class="animate-spin rounded-full h-10 w-10 border-t-2 border-b-2 border-brand-500"></div>
    </div>

    <!-- Error State -->
    <div v-else-if="error" class="bg-red-500/10 border border-red-500/20 rounded-2xl p-6 text-center">
      <i class="fas fa-exclamation-triangle text-red-600 text-3xl mb-3"></i>
      <h3 class="text-lg font-medium text-slate-800 mb-1">Failed to load configuration</h3>
      <p class="text-red-300 text-sm mb-4">{{ error }}</p>
      <button @click="fetchSetup" class="px-4 py-2 bg-slate-100 hover:bg-slate-100 text-slate-800 rounded-lg text-sm transition-colors">
        Try Again
      </button>
    </div>

    <!-- Success Message -->
    <div v-if="successMessage" class="bg-emerald-500/10 border border-emerald-500/20 rounded-xl p-4 flex items-center gap-3 animate-fade-in-up">
      <i class="fas fa-check-circle text-emerald-600 text-xl"></i>
      <p class="text-emerald-600 font-medium text-sm">{{ successMessage }}</p>
    </div>

    <div v-if="!loading && !error" class="max-w-3xl glass-panel rounded-3xl overflow-hidden border border-slate-200/60 shadow-xl">
      <!-- 2FA Enabled State -->
      <div v-if="isEnabled" class="p-10 text-center relative overflow-hidden">
        <!-- Glow Effect -->
        <div class="absolute top-0 left-1/2 -translate-x-1/2 w-64 h-32 bg-emerald-500/10 blur-[60px] rounded-full pointer-events-none"></div>

        <div class="h-24 w-24 bg-gradient-to-br from-emerald-500/20 to-emerald-600/10 text-emerald-600 rounded-full flex items-center justify-center mx-auto mb-6 text-4xl shadow-lg border border-emerald-500/30">
          <i class="fas fa-check"></i>
        </div>
        <h3 class="text-2xl font-extrabold text-slate-800">2FA is currently active</h3>
        <p class="text-slate-500 mt-3 text-sm max-w-md mx-auto leading-relaxed">
          Your account is secured with Two-Factor Authentication. If you wish to use a different device or disable this feature, click below.
        </p>
        
        <div class="mt-8">
          <button @click="showDisableModal = true" class="px-8 py-3.5 bg-red-500/10 hover:bg-red-500/20 text-red-600 font-bold rounded-xl border border-red-500/30 transition-all shadow-lg hover:shadow-red-500/10 flex items-center justify-center gap-2 mx-auto">
            <i class="fas fa-power-off"></i> Disable 2FA
          </button>
        </div>
      </div>

      <!-- 2FA Setup State -->
      <div v-else class="p-8">
        <ol class="list-decimal list-inside space-y-8 text-slate-500 text-sm">
          <li class="pl-2">
            <strong class="text-slate-800 text-base">Download an Authenticator App</strong>
            <p class="text-slate-500 ml-5 mt-2">Download Google Authenticator, Authy, or Microsoft Authenticator on your mobile device.</p>
          </li>
          <li class="pl-2">
            <strong class="text-slate-800 text-base">Scan the QR Code</strong>
            <p class="text-slate-500 ml-5 mt-2">Open your authenticator app and scan the QR code below.</p>
            <div class="flex justify-center mt-6">
              <div class="p-6 bg-white rounded-2xl shadow-lg ring-4 ring-slate-800/50">
                <div v-html="qrCodeUrl" class="[&>svg]:w-48 [&>svg]:h-48 mx-auto flex justify-center"></div>
              </div>
            </div>
            <div class="text-center mt-4 bg-slate-100/60 rounded-lg py-2 px-4 inline-block mx-auto max-w-max border border-slate-200/60">
              <span class="text-xs text-slate-500 uppercase tracking-wider font-semibold mr-2">Secret Key:</span>
              <span class="text-brand-600 font-mono tracking-widest">{{ secret }}</span>
            </div>
          </li>
          <li class="pl-2">
            <strong class="text-slate-800 text-base">Verify Setup</strong>
            <p class="text-slate-500 ml-5 mt-2 mb-4">Enter the 6-digit code generated by your app to verify and enable 2FA.</p>
            
            <form @submit.prevent="verifyCode" class="ml-5">
              <div class="flex flex-col sm:flex-row gap-3 max-w-sm">
                <input 
                  type="text" 
                  v-model="oneTimePassword"
                  placeholder="------" 
                  required 
                  maxlength="6"
                  autocomplete="off" 
                  class="flex-1 px-4 py-3 rounded-xl border-slate-600 bg-slate-100 text-slate-800 focus:border-brand-500 focus:ring-brand-500 text-center text-2xl tracking-[0.5em] font-mono shadow-inner placeholder-slate-400"
                >
                <button 
                  type="submit" 
                  :disabled="verifying"
                  class="px-8 py-3 bg-brand-500 hover:bg-brand-400 disabled:opacity-50 text-white font-extrabold rounded-xl shadow-lg shadow-brand-500/25 transition-all flex items-center justify-center min-w-[120px]"
                >
                  <span v-if="verifying" class="animate-spin mr-2"><i class="fas fa-circle-notch"></i></span>
                  <span v-else>Verify</span>
                </button>
              </div>
              <p v-if="verifyError" class="text-red-600 text-sm mt-3 font-medium">{{ verifyError }}</p>
            </form>
          </li>
        </ol>
      </div>
    </div>

    <!-- Disable Modal -->
    <div v-if="showDisableModal" class="fixed inset-0 z-50 overflow-y-auto" aria-labelledby="modal-title" role="dialog" aria-modal="true">
      <div class="flex items-end justify-center min-h-screen px-4 pt-4 pb-20 text-center sm:block sm:p-0">
        <div class="fixed inset-0 transition-opacity bg-slate-50 backdrop-blur-sm" @click="showDisableModal = false" aria-hidden="true"></div>

        <span class="hidden sm:inline-block sm:align-middle sm:h-screen" aria-hidden="true">&#8203;</span>

        <div class="inline-block px-4 pt-5 pb-4 overflow-hidden text-left align-bottom transition-all transform bg-white rounded-2xl shadow-2xl sm:my-8 sm:align-middle sm:max-w-lg sm:w-full sm:p-6 border border-slate-200/60">
          <div class="sm:flex sm:items-start">
            <div class="flex items-center justify-center flex-shrink-0 w-12 h-12 mx-auto bg-red-500/20 rounded-full sm:mx-0 sm:h-10 sm:w-10 text-red-600 border border-red-500/30">
              <i class="fas fa-exclamation-triangle"></i>
            </div>
            <div class="mt-3 text-center sm:mt-0 sm:ml-4 sm:text-left">
              <h3 class="text-lg font-bold leading-6 text-slate-800" id="modal-title">Disable Two-Factor Authentication</h3>
              <div class="mt-2">
                <p class="text-sm text-slate-500 leading-relaxed">Are you sure you want to disable 2FA? This will significantly reduce the security of your account and leave it vulnerable to unauthorized access.</p>
              </div>
            </div>
          </div>
          <div class="mt-6 sm:mt-5 sm:flex sm:flex-row-reverse gap-3">
            <button 
              @click="disable2FA" 
              :disabled="disabling"
              class="w-full inline-flex justify-center items-center rounded-xl border border-transparent shadow-sm px-4 py-2.5 bg-red-600 hover:bg-red-500 text-base font-bold text-white focus:outline-none focus:ring-2 focus:ring-offset-2 focus:ring-red-500 sm:w-auto sm:text-sm disabled:opacity-50 transition-colors"
            >
              <span v-if="disabling" class="animate-spin mr-2"><i class="fas fa-circle-notch"></i></span>
              Yes, Disable 2FA
            </button>
            <button 
              @click="showDisableModal = false" 
              type="button" 
              class="mt-3 w-full inline-flex justify-center rounded-xl border border-slate-600 shadow-sm px-4 py-2.5 bg-slate-100 hover:bg-slate-100 text-base font-medium text-slate-500 focus:outline-none focus:ring-2 focus:ring-offset-2 focus:ring-slate-500 sm:mt-0 sm:w-auto sm:text-sm transition-colors"
            >
              Cancel
            </button>
          </div>
        </div>
      </div>
    </div>
  </div>
</template>

<script>
import { ref, onMounted } from 'vue';
import axios from 'axios';

export default {
  name: 'TwoFactorSetupView',
  setup() {
    const loading = ref(true);
    const error = ref(null);
    const successMessage = ref(null);
    
    const isEnabled = ref(false);
    const qrCodeUrl = ref('');
    const secret = ref('');
    
    const oneTimePassword = ref('');
    const verifying = ref(false);
    const verifyError = ref(null);
    
    const showDisableModal = ref(false);
    const disabling = ref(false);

    const showSuccess = (msg) => {
      successMessage.value = msg;
      setTimeout(() => { successMessage.value = null; }, 5000);
    };

    const fetchSetup = async () => {
      loading.value = true;
      error.value = null;
      try {
        const response = await axios.get('/portal/api/2fa-setup', {
          headers: { 'Accept': 'application/json' }
        });
        isEnabled.value = response.data.is_enabled;
        qrCodeUrl.value = response.data.qrCodeUrl;
        secret.value = response.data.secret;
      } catch (err) {
        error.value = err.response?.data?.message || 'An error occurred while fetching 2FA configuration.';
      } finally {
        loading.value = false;
      }
    };

    const verifyCode = async () => {
      if (oneTimePassword.value.length !== 6) {
        verifyError.value = 'Please enter a 6-digit code.';
        return;
      }
      
      verifying.value = true;
      verifyError.value = null;
      
      try {
        const response = await axios.post('/portal/api/2fa-confirm', {
          one_time_password: oneTimePassword.value
        }, { headers: { 'Accept': 'application/json' } });
        
        isEnabled.value = true;
        oneTimePassword.value = '';
        showSuccess(response.data.message || 'Two-Factor Authentication enabled successfully!');
      } catch (err) {
        if (err.response?.status === 422) {
          verifyError.value = err.response.data.errors?.one_time_password?.[0] || 'Invalid code.';
        } else {
          verifyError.value = 'An error occurred. Please try again.';
        }
      } finally {
        verifying.value = false;
      }
    };

    const disable2FA = async () => {
      disabling.value = true;
      try {
        const response = await axios.post('/portal/api/2fa-disable', {}, { headers: { 'Accept': 'application/json' } });
        isEnabled.value = false;
        showDisableModal.value = false;
        showSuccess(response.data.message || 'Two-Factor Authentication has been disabled.');
      } catch (err) {
        error.value = 'Failed to disable 2FA. Please try again.';
      } finally {
        disabling.value = false;
      }
    };

    onMounted(() => {
      fetchSetup();
    });

    return {
      loading,
      error,
      successMessage,
      isEnabled,
      qrCodeUrl,
      secret,
      oneTimePassword,
      verifying,
      verifyError,
      showDisableModal,
      disabling,
      fetchSetup,
      verifyCode,
      disable2FA
    };
  }
};
</script>

